#!/usr/bin/env python3
"""
SDOM Manual Checkin Workflow
============================

Separate workflow for manual (non-gen) FC parts. Uses different naming conventions
and configuration than generated (_GEN) FC parts.

MANUAL (non-gen) naming:
  - SW-FEATURE-VARIANT: EcuDiag_InjMngt_H2InjrLo (no _GEN suffix)
  - Export interface: EcuDiag_InjMngt_H2InjrLo_Ex (no _GEN)
  - Import interface: EcuDiag_InjMngt_H2InjrLo_Im (no _GEN)
  - SDOM fullNames: TDATA:InjMngt_H2InjrLo/358.0.0;0, SPEC:InjMngt_H2InjrLo/358.1.0;0

Usage:
  python sdom_manual_checkin.py \\
    --workspace-dir <path> \\
    --sdom-user <username> \\
    --sdom-password <password> \\
    --fc-fullname "SwEcu:InjMngt_H2InjrLo.cont/1.0.0;0"
"""

import json
import csv
import sys
import logging
from pathlib import Path
from typing import Dict, List, Tuple, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(levelname)s | %(message)s'
)
logger = logging.getLogger(__name__)


class ManualCheckinWorkflow:
    """Orchestrate manual checkin of C/header/PaVaSt/TDOC files."""

    def __init__(self, workspace_dir: str, fc_fullname: str):
        """Initialize manual checkin workflow.
        
        Args:
            workspace_dir: Root directory of checked-out FC workspace
            fc_fullname: Full SDOM name of FC container (e.g., "SwEcu:InjMngt_H2InjrLo.cont/1.0.0;0")
        """
        self.workspace_dir = Path(workspace_dir)
        self.fc_fullname = fc_fullname
        self.changed_files = []
        
        # Extract FC name from fullname for file references
        # Example: "SwEcu:InjMngt_H2InjrLo.cont/1.0.0;0" -> "InjMngt_H2InjrLo"
        self.fc_name = self._extract_fc_name()
        
    def _extract_fc_name(self) -> str:
        """Extract FC name from fullname.
        
        Example: "SwEcu:InjMngt_H2InjrLo.cont/1.0.0;0" -> "InjMngt_H2InjrLo"
        """
        parts = self.fc_fullname.split(':')
        if len(parts) >= 2:
            name_part = parts[1].split('.cont')[0]
            return name_part
        return "Unknown"

    def load_changed_files(self, changed_files_csv: str) -> bool:
        """Load list of changed files from CSV (generated by prepare-import).
        
        Filters for MANUAL (non-gen) files only, excluding _gen.cont files.
        
        Args:
            changed_files_csv: Path to CSV with changed files
            
        Returns:
            True if loaded successfully
        """
        csv_path = Path(changed_files_csv)
        if not csv_path.exists():
            logger.error(f"Changed files CSV not found: {changed_files_csv}")
            return False
            
        try:
            with open(csv_path, 'r', encoding='utf-8') as f:
                reader = csv.DictReader(f)
                for row in reader:
                    filename = row.get('file_name', '').lower()
                    filepath = row.get('file_path', '')
                    
                    # Skip generated (_gen) files - manual workflow only
                    if '_gen' in filename or '_gen.cont' in filepath:
                        continue
                    
                    self.changed_files.append({
                        'path': filepath,
                        'filename': filename,
                        'root_fullname': row.get('root_fullname', ''),
                        'change_type': row.get('change_type', '')
                    })
            
            logger.info(f"✓ Loaded {len(self.changed_files)} MANUAL changed file(s) from {csv_path.name}")
            return True
        except Exception as e:
            logger.error(f"Failed to load changed files: {e}")
            return False

    def build_import_batch(self) -> Dict:
        """Build import batch configuration for manual checkin.
        
        Maps changed files to SDOM objects using MANUAL naming (no _GEN suffix).
        
        Returns:
            Dictionary with import batch structure for manual files
        """
        batch = {
            "fc_fullname": self.fc_fullname,
            "workflow_type": "manual",
            "objects": []
        }
        
        # Map changed files to SDOM objects (manual naming)
        for cf in self.changed_files:
            filename = cf['filename']
            filepath = cf['path']
            
            # C file: maps to FC's SWSRC child object
            if filename.endswith('.c'):
                batch['objects'].append({
                    'type': 'SWSRC',
                    'name': f"{self.fc_name}",  # No _GEN suffix for manual
                    'path': filepath,
                    'action': 'replace'
                })
                logger.info(f"  ✓ Mapped C file → SWSRC: {self.fc_name}")
            
            # Header file: maps to FC's SWHDR child object
            elif filename.endswith('.h'):
                batch['objects'].append({
                    'type': 'SWHDR',
                    'name': f"{self.fc_name}",  # No _GEN suffix for manual
                    'path': filepath,
                    'action': 'replace'
                })
                logger.info(f"  ✓ Mapped header file → SWHDR: {self.fc_name}")
            
            # PaVaSt file: maps to TDATA object with manual naming
            elif 'pavast' in filename and filename.endswith('.xml'):
                batch['objects'].append({
                    'type': 'TDATA',
                    'fullname': f"TDATA:{self.fc_name}/358.0.0;0",  # Manual naming (no _GEN)
                    'path': filepath,
                    'action': 'replace'
                })
                logger.info(f"  ✓ Mapped PaVaSt file → TDATA: {self.fc_name}/358.0.0;0")
            
            # TDOC file (_fs.xml): maps to SPEC object with manual naming
            elif filename.endswith('_fs.xml'):
                batch['objects'].append({
                    'type': 'SPEC',
                    'fullname': f"SPEC:{self.fc_name}/358.1.0;0",  # Manual naming (no _GEN)
                    'path': filepath,
                    'action': 'replace'
                })
                logger.info(f"  ✓ Mapped TDOC file → SPEC: {self.fc_name}/358.1.0;0")
        
        return batch

    def validate_batch(self, batch: Dict) -> Tuple[bool, str]:
        """Validate import batch configuration.
        
        Args:
            batch: Import batch dictionary
            
        Returns:
            Tuple (is_valid, error_message)
        """
        if not batch['objects']:
            return False, "No objects in batch"
        
        # Require at least C code (SWSRC) and PaVaSt (TDATA) for manual workflow
        # Header (SWHDR) and TDOC (SPEC) are optional if not detected as changed
        required_types = {'SWSRC', 'TDATA'}
        found_types = {obj['type'] for obj in batch['objects']}
        
        if not required_types.issubset(found_types):
            missing = required_types - found_types
            return False, f"Missing required object types: {missing}"
        
        return True, "OK"

    def print_batch_summary(self, batch: Dict) -> None:
        """Print summary of import batch."""
        logger.info("")
        logger.info("═" * 70)
        logger.info("MANUAL CHECKIN BATCH SUMMARY")
        logger.info("═" * 70)
        logger.info(f"FC: {self.fc_fullname}")
        logger.info(f"Workflow: {batch['workflow_type'].upper()}")
        logger.info("")
        
        for obj in batch['objects']:
            logger.info(f"  [{obj['type']}] {obj.get('fullname', obj.get('name'))}")
            logger.info(f"    Path: {obj['path']}")
            logger.info(f"    Action: {obj['action']}")
            logger.info("")
        
        logger.info("═" * 70)

    def run(self, changed_files_csv: str) -> bool:
        """Execute manual checkin workflow.
        
        Args:
            changed_files_csv: Path to CSV with changed files
            
        Returns:
            True if workflow completed successfully
        """
        logger.info("")
        logger.info("╔════════════════════════════════════════════╗")
        logger.info("║  MANUAL CHECKIN WORKFLOW (Non-Gen FC Part) ║")
        logger.info("╚════════════════════════════════════════════╝")
        logger.info("")
        
        # Load changed files
        if not self.load_changed_files(changed_files_csv):
            return False
        
        # Build import batch
        batch = self.build_import_batch()
        logger.info(f"✓ Built import batch with {len(batch['objects'])} object(s)")
        
        # Validate batch
        is_valid, msg = self.validate_batch(batch)
        if not is_valid:
            logger.error(f"✗ Batch validation failed: {msg}")
            return False
        
        logger.info("✓ Batch validation passed")
        
        # Print summary
        self.print_batch_summary(batch)
        
        # Save batch config for SDOM import
        batch_json = self.workspace_dir / "import_batch.json"
        try:
            with open(batch_json, 'w', encoding='utf-8') as f:
                json.dump(batch, f, indent=2)
            logger.info(f"✓ Import batch saved to {batch_json.name}")
        except Exception as e:
            logger.error(f"Failed to save batch: {e}")
            return False
        
        logger.info("")
        logger.info("✓ Manual checkin workflow ready")
        logger.info(f"  Next: Run sdom_Checkin.py with import batch")
        logger.info("")
        
        return True


def main():
    import argparse
    
    parser = argparse.ArgumentParser(
        description='SDOM Manual Checkin Workflow for non-Gen FC parts',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python sdom_manual_checkin.py \\
    --workspace-dir "./checkout_workspace" \\
    --changed-files "./checkout_workspace/changed_files.csv" \\
    --fc-fullname "SwEcu:InjMngt_H2InjrLo.cont/1.0.0;0"
        """
    )
    
    parser.add_argument('--workspace-dir', required=True,
                       help='Root directory of checked-out FC workspace')
    parser.add_argument('--changed-files', required=True,
                       help='Path to changed_files.csv (from prepare-import)')
    parser.add_argument('--fc-fullname', required=True,
                       help='Full SDOM name of FC container')
    
    args = parser.parse_args()
    
    workflow = ManualCheckinWorkflow(args.workspace_dir, args.fc_fullname)
    success = workflow.run(args.changed_files)
    
    sys.exit(0 if success else 1)


if __name__ == '__main__':
    main()
